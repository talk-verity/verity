import html
import logging
from datetime import datetime

logger = logging.getLogger(__name__)


class ReportRenderer:
    def render_html(self, content: dict) -> str:
        try:
            score = content.get("overall_score", 0)
            summary = content.get("summary", "")
            goal = content.get("goal_completion", "")
            strengths = content.get("strengths", []) or []
            weaknesses = content.get("weaknesses", []) or []
            recommendations = content.get("recommendations", []) or []
            suggested = content.get("suggested_responses", []) or []
            metrics = content.get("metrics", {}) or {}
            examples = content.get("transcript_examples", []) or []
            references = content.get("references", []) or []

            sections = []
            sections.append('<h1>Overall Summary</h1><p>' + html.escape(content.get("assessment_note") or "Legacy heuristic report: numerical scores are not validated and are hidden.") + '</p>')
            observations = content.get("rubric_observations", [])
            if observations:
                sections.append('<h2>Practice prompts</h2><ul>' + ''.join('<li>' + html.escape(o["criterion"]) + ': ' + ('text cue found' if o["observed"] else 'review your transcript') + '</li>' for o in observations) + '</ul>')
            sections.append(self._metric_section(metrics))
            sections.append(self._strengths_section(strengths, examples))
            sections.append(self._improvements_section(weaknesses, examples))
            sections.append(self._next_steps_section(recommendations, references))
            sections.append(self._suggested_responses_section(suggested))
            sections.append(self._transcript_examples_section(examples))

            body = "\n".join(s for s in sections if s)
            title = html.escape(content.get("scenario", "Verity Report"))
            return self._wrap(title, body)
        except Exception as e:
            logger.error("Report render failed: %s", e)
            raise

    def _wrap(self, title: str, body: str) -> str:
        return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>{title}</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
         max-width: 720px; margin: 0 auto; padding: 32px 20px; color: #18181b;
         line-height: 1.6; background: #ffffff; }}
  h1 {{ font-size: 1.5rem; margin-bottom: 4px; }}
  h2 {{ font-size: 1.05rem; margin: 28px 0 12px; border-bottom: 1px solid #e4e4e7; padding-bottom: 6px; }}
  .meta {{ color: #71717a; font-size: .85rem; margin-bottom: 20px; }}
  .score {{ font-size: 3rem; font-weight: 700; margin: 8px 0; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(140px, 1fr)); gap: 10px; }}
  .card {{ background: #fafafa; border: 1px solid #e4e4e7; border-radius: 12px; padding: 12px 14px; }}
  .card .label {{ font-size: .72rem; text-transform: uppercase; letter-spacing: .05em; color: #71717a; }}
  .card .value {{ font-size: 1.1rem; font-weight: 600; margin-top: 2px; }}
  ul {{ margin: 8px 0; padding-left: 20px; }}
  li {{ margin: 6px 0; }}
  .strength {{ color: #15803d; }}
  .weakness {{ color: #b45309; }}
  .quote {{ background: #f4f4f5; border-left: 3px solid #a1a1aa; padding: 8px 12px; margin: 8px 0;
           border-radius: 0 8px 8px 0; font-style: italic; color: #3f3f46; }}
  .tag {{ display: inline-block; font-size: .72rem; padding: 2px 8px; border-radius: 999px; margin-right: 6px; }}
  .tag.strength {{ background: #dcfce7; color: #166534; }}
  .tag.weakness {{ background: #fef3c7; color: #92400e; }}
  .ref {{ font-size: .82rem; color: #52525b; background: #f4f4f5; border-radius: 8px; padding: 8px 10px; margin: 6px 0; }}
  .footer {{ margin-top: 40px; color: #a1a1aa; font-size: .75rem; }}
</style>
</head>
<body>
{body}
<div class="footer">Generated by Verity · {html.escape(str(datetime.now().strftime("%B %d, %Y %H:%M")))}</div>
</body>
</html>"""

    def _score_section(self, score, summary, goal) -> str:
        goal_line = f'<p>Goal completion: <strong>{html.escape(str(goal))}</strong></p>' if goal else ""
        summary_html = f"<p>{html.escape(summary)}</p>" if summary else ""
        return f"""
<h1>Overall Summary</h1>
<div class="score">{html.escape(str(score))}<span style="font-size:1rem;color:#71717a">/100</span></div>
{goal_line}
{summary_html}"""

    def _metric_section(self, metrics) -> str:
        items = {
            "Filler words": metrics.get("filler_word_count"),
            "Turns": metrics.get("total_turns"),
            "Avg response length": metrics.get("avg_response_length"),
        }
        cards = "\n".join(
            f'<div class="card"><div class="label">{k}</div><div class="value">{html.escape(str(v))}</div></div>'
            for k, v in items.items() if v is not None
        )
        if not cards:
            return ""
        return f"<h2>Metrics</h2>\n<div class=\"grid\">\n{cards}\n</div>"

    def _strengths_section(self, strengths, examples) -> str:
        if not strengths:
            return ""
        lis = "\n".join(f'<li class="strength">{html.escape(s)}</li>' for s in strengths)
        return f"<h2>Strengths</h2>\n<ul>\n{lis}\n</ul>"

    def _improvements_section(self, weaknesses, examples) -> str:
        if not weaknesses:
            return ""
        lis = "\n".join(f'<li class="weakness">{html.escape(w)}</li>' for w in weaknesses)
        return f"<h2>Areas to Improve</h2>\n<ul>\n{lis}\n</ul>"

    def _next_steps_section(self, recommendations, references) -> str:
        if not recommendations and not references:
            return ""
        parts = ["<h2>Suggested Next Steps</h2>"]
        if recommendations:
            lis = "\n".join(f"<li>{html.escape(r)}</li>" for r in recommendations)
            parts.append(f"<ul>\n{lis}\n</ul>")
        if references:
            parts.append("<div style=\"font-size:.85rem;color:#52525b;margin-top:12px\">Grounded in:</div>")
            for ref in references[:5]:
                parts.append(f'<div class="ref">📎 {html.escape(str(ref.get("source", "")))} — {html.escape(str(ref.get("snippet", "")))}</div>')
        return "\n".join(parts)

    def _suggested_responses_section(self, suggested) -> str:
        if not suggested:
            return ""
        blocks = []
        for item in suggested:
            weakness = html.escape(str(item.get("weakness", "")))
            response = html.escape(str(item.get("response", "")))
            source = html.escape(str(item.get("source", "")))
            source_line = f'<div style="font-size:.78rem;color:#71717a;margin-top:4px">Source: {source}</div>' if source else ""
            blocks.append(
                f'<div class="quote"><span class="tag weakness">{"For " + weakness if weakness else "Suggested response"}</span>'
                f'{response}{source_line}</div>'
            )
        return "<h2>Practice suggestions</h2>\n" + "\n".join(blocks)

    def _transcript_examples_section(self, examples) -> str:
        if not examples:
            return ""
        blocks = []
        for ex in examples:
            kind = ex.get("type", "")
            cls = "strength" if kind == "strength" else "weakness"
            label = html.escape(str(ex.get("label", "")))
            quote = html.escape(str(ex.get("quote", "")))
            blocks.append(
                f'<div class="quote"><span class="tag {cls}">{label}</span>{quote}</div>'
            )
        return "<h2>Transcript References</h2>\n" + "\n".join(blocks)


renderer = ReportRenderer()
